"""Pure Phase 7 recommendation builder: combines the risk profile (step 1),
asset split (step 2), equity weights (steps 3-4) and funds (step 5) into
rupee amounts, reasons and a risk summary. No I/O, so every rule here is
unit-tested directly; recommendation_service.py gathers the inputs.
"""

from datetime import datetime
from statistics import median

from app.core.constants import SECTORS, TICKER_TO_COMPANY_NAME
from app.core.portfolio_config import MAX_SECTOR_WEIGHT, MAX_STOCK_WEIGHT, SENTIMENT_MIN_ARTICLES
from app.services.fund_meta_provider import PLACEHOLDER_MF_MIN_INVESTMENT, PLACEHOLDER_MF_MIN_SIP

RECOMMENDATION_VERSION = "rec-v1"

# A loss this many standard deviations below zero happens in about 1 year
# in 20 if yearly returns were normally distributed. Real markets have
# fatter tails, so this is a floor on how bad a bad year can be, not a cap.
BAD_YEAR_Z = 1.65

# A weight change from sentiment smaller than this isn't worth mentioning.
NOTABLE_TILT = 0.005

DISCLAIMER = (
    "Educational illustration generated by rules and past data, not investment advice. "
    "IntelliVest is not a SEBI-registered investment adviser. Past behaviour does not "
    "predict future returns; check costs and suitability before investing."
)


def split_amount(total: float, weights: list[float]) -> list[int]:
    """Whole rupees per weight that add up exactly to round(total)."""
    total_rupees = round(total)
    raw = [total * w for w in weights]
    amounts = [int(r) for r in raw]
    # Hand leftover rupees to the largest fractional parts.
    order = sorted(range(len(raw)), key=lambda i: raw[i] - amounts[i], reverse=True)
    for i in order[: total_rupees - sum(amounts)]:
        amounts[i] += 1
    return amounts


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def _stock_reasons(stock: dict, equity: dict, stats: dict, held: list[str], signal: dict) -> list[str]:
    ticker = stock["ticker"]
    reasons = []
    vols = [stats["stocks"][t]["annual_volatility"] for t in stats["tickers"]]
    vol = stats["stocks"][ticker]["annual_volatility"]
    if vol <= median(vols):
        reasons.append(f"One of the calmer stocks: {_pct(vol)} yearly volatility "
                       f"(median of tracked stocks {_pct(median(vols))}).")
    others = [t for t in held if t != ticker]
    if others:
        avg_corr = sum(stats["correlation"][ticker][t] for t in others) / len(others)
        if avg_corr < stats["average_correlation"]:
            reasons.append(f"Moves less in step with the other holdings than most stocks do "
                           f"(average correlation {avg_corr:.2f}).")
    if stock["min_variance_weight"] >= MAX_STOCK_WEIGHT - 1e-4:
        reasons.append(f"Held at the {_pct(MAX_STOCK_WEIGHT)} limit per stock.")
    sector = stock["sector"]
    if equity["portfolio"]["sector_weights"].get(sector, 0) >= MAX_SECTOR_WEIGHT - 1e-4:
        reasons.append(f"Its sector ({SECTORS[sector][0]}) is at the {_pct(MAX_SECTOR_WEIGHT)} "
                       "sector limit.")
    tilt = stock["weight"] - stock["min_variance_weight"]
    if abs(tilt) >= NOTABLE_TILT:
        direction = "Raised" if tilt > 0 else "Lowered"
        reasons.append(
            f"{direction} by {abs(tilt) * 100:.1f} points for its recent news compared with the "
            f"other holdings (average FinBERT score {stock['sentiment_score']:+.2f} across "
            f"{signal.get('article_count', 0)} articles)."
        )
    if not reasons:
        reasons.append("Lowers the overall volatility of the stock part within the limits.")
    return reasons


def _fund_reasons(fund: dict, allocation: dict) -> list[str]:
    figures = []
    if fund.get("return_3y") is not None:
        figures.append(f"{_pct(fund['return_3y'])} a year over 3 years")
    if fund.get("annual_volatility") is not None:
        figures.append(f"{_pct(fund['annual_volatility'])} yearly volatility")
    if fund.get("max_drawdown_3y") is not None:
        figures.append(f"worst fall {_pct(fund['max_drawdown_3y'])} in 3 years")
    adjustments = [a["reason"] for a in allocation["adjustments"]]
    reasons = [f"{fund['role_label']} for the {'gold' if fund['role'] == 'gold' else 'debt'} part."]
    reasons += adjustments if fund["role"] != "gold" else []
    if figures:
        reasons.append("Past behaviour: " + ", ".join(figures) + ".")
    return reasons


def _minimum_warnings(asset: str, lump: int, monthly: int, price: float | None) -> list[str]:
    warnings = []
    if asset == "equity":
        if price:
            for label, amount in (("one-time amount", lump), ("monthly amount", monthly)):
                if 0 < amount < price:
                    warnings.append(f"The {label} (₹{amount:,}) is less than one share (₹{price:,.0f}).")
    else:
        if 0 < lump < PLACEHOLDER_MF_MIN_INVESTMENT:
            warnings.append(f"Below the usual ₹{PLACEHOLDER_MF_MIN_INVESTMENT:,} minimum one-time investment.")
        if 0 < monthly < PLACEHOLDER_MF_MIN_SIP:
            warnings.append(f"Below the usual ₹{PLACEHOLDER_MF_MIN_SIP:,} minimum SIP.")
    return warnings


def build_recommendation(
    *,
    profile: dict,
    allocation: dict,
    equity: dict | None,
    stats: dict | None,
    signals: dict[str, dict],
    funds: dict[str, dict],
    lump_sum: float,
    monthly_sip: float,
    stock_prices: dict[str, float | None],
    current_holdings: list[dict],
    goal: dict | None,
    created_at: datetime,
) -> dict:
    lines = []  # (asset class, weight of whole portfolio, line details)

    if equity is not None:
        held = [s["ticker"] for s in equity["stocks"] if s["weight"] > 0]
        for stock in equity["stocks"]:
            if stock["weight"] <= 0:
                continue
            ticker = stock["ticker"]
            lines.append(("equity", allocation["equity_pct"] / 100 * stock["weight"], {
                "instrument_id": f"stock-{ticker}",
                "name": TICKER_TO_COMPANY_NAME.get(ticker, ticker),
                "kind": "stock",
                "sector": stock["sector"],
                "weight_in_class": stock["weight"],
                "reasons": _stock_reasons(stock, equity, stats, held, signals.get(ticker, {})),
            }))

    for role, pct in ((allocation["debt_style"], allocation["debt_pct"]), ("gold", allocation["gold_pct"])):
        if pct <= 0:
            continue
        fund = funds[role]
        asset = "gold" if role == "gold" else "debt"
        lines.append((asset, pct / 100, {
            "instrument_id": fund.get("instrument_id"),
            "name": fund.get("name") or f"{fund['role_label']} (no fund available right now)",
            "kind": "fund",
            "fund_role": role,
            "weight_in_class": 1.0,
            "reasons": _fund_reasons(fund, allocation) if fund.get("instrument_id") else [
                "No listed fund passed today's checks: " + "; ".join(s["reason"] for s in fund["skipped"])
            ],
        }))

    weights = [w for _, w, _ in lines]
    lumps, monthlies = split_amount(lump_sum, weights), split_amount(monthly_sip, weights)
    current = {h["instrument_id"]: h for h in current_holdings}
    holdings = []
    for (asset, weight, line), lump, monthly in zip(lines, lumps, monthlies, strict=True):
        ticker = line["instrument_id"].removeprefix("stock-") if line["kind"] == "stock" else None
        existing = current.get(line["instrument_id"])
        holdings.append({
            "asset_class": asset,
            **line,
            "weight": round(weight, 4),
            "lump_sum_amount": lump,
            "monthly_amount": monthly,
            "already_held_value": existing.get("current_value") if existing else None,
            "warnings": _minimum_warnings(asset, lump, monthly, stock_prices.get(ticker) if ticker else None),
        })

    stock_lines = [h for h in holdings if h["kind"] == "stock"]
    notes = []
    if stock_lines and sum(bool(h["warnings"]) for h in stock_lines) > len(stock_lines) / 2:
        notes.append("At this amount most stocks cost more than their share. A Nifty 50 index fund "
                     "can hold the equity part instead, for any amount.")
    if equity is not None and not equity["sentiment_used"]:
        notes.append("News sentiment wasn't used (switched off, or too few scored articles).")

    # Risk: each part's volatility, combined as if the parts moved together
    # (correlation 1). We don't estimate cross-asset correlations yet, so
    # this is an upper bound; diversification across parts lowers it.
    class_vol = {
        "equity": equity["portfolio"]["annual_volatility"] if equity else None,
        "debt": funds.get(allocation["debt_style"], {}).get("annual_volatility"),
        "gold": funds.get("gold", {}).get("annual_volatility"),
    }
    class_pct = {"equity": allocation["equity_pct"], "debt": allocation["debt_pct"], "gold": allocation["gold_pct"]}
    missing = [c for c, p in class_pct.items() if p > 0 and class_vol[c] is None]
    upper = None if missing else round(sum(class_pct[c] / 100 * (class_vol[c] or 0) for c in class_pct), 6)

    recommended_ids = {h["instrument_id"] for h in holdings}
    return {
        "inputs": {"lump_sum": round(lump_sum), "monthly_sip": round(monthly_sip),
                   "horizon_months": allocation["horizon_months"],
                   "goal": {"id": goal["id"], "name": goal["name"]} if goal else None},
        "profile": {k: profile[k] for k in ("profile", "label", "capacity_score", "tolerance_score", "limited_by")},
        "allocation": allocation,
        "holdings": holdings,
        "risk": {
            "class_volatility": class_vol,
            "volatility_upper_bound": upper,
            "bad_year_loss": round(-BAD_YEAR_Z * upper, 4) if upper is not None else None,
            "explanation": (
                "Volatility is how much the portfolio's value swings in a typical year. The parts "
                "are combined as if they always moved together, so the real figure is likely "
                "lower. A bad year (about 1 in 20) could lose roughly the 'bad year' figure; "
                "rarer years can lose more."
            ),
            "missing": missing,
        },
        "equity_comparison": None if equity is None else {
            "optimized": equity["portfolio"],
            "minimum_variance": equity["min_variance"],
            "equal_weight": equity["equal_weight"],
        },
        "not_held": [
            {"instrument_id": h["instrument_id"], "name": h["instrument_name"],
             "current_value": h.get("current_value")}
            for h in current_holdings if h["instrument_id"] not in recommended_ids
        ],
        "notes": notes,
        "versions": {
            "recommendation": RECOMMENDATION_VERSION,
            "risk_questionnaire": profile.get("version"),
            "allocation": allocation["version"],
            "optimizer": equity["version"] if equity else None,
            "market_stats_as_of": stats["as_of"] if stats else None,
            "sentiment_min_articles": SENTIMENT_MIN_ARTICLES,
        },
        "disclaimer": DISCLAIMER,
        "created_at": created_at,
    }
