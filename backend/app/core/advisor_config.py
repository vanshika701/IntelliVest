"""Phase 9 advisor settings: the ONE place to edit timeouts, freshness rules
and which modules the advisor reads. Our own choices, not from a source.
"""

ADVISOR_VERSION = "advisor-v1"

# Each module must answer within this many seconds or it is reported as
# unavailable and the advice is marked partial. Holdings can fetch fund NAVs
# over the network (cached), so it gets longer.
MODULE_TIMEOUT_SECONDS = 5.0
MODULE_TIMEOUTS_SECONDS: dict[str, float] = {"holdings": 10.0}

# Data older than this is still used, but reported as stale.
STALE_AFTER_DAYS: dict[str, int] = {
    "sectors": 7,
    "sentiment": 7,
    "predictions": 7,
    # A portfolio plan is rebuilt by the user; after a month prices, profile
    # or goals have likely moved on.
    "portfolio_plan": 30,
}

# The prediction horizon the advisor shows ranges for: one year.
PREDICTION_HORIZON_TRADING_DAYS = 252

# Fund names containing these words are classed as debt or gold when a
# holding isn't one of the configured Phase 7 funds. Anything else that
# isn't a stock is "unclassified" and left out of drift checks rather than
# guessed.
DEBT_FUND_WORDS = (
    "liquid", "debt", "bond", "gilt", "duration", "money market", "overnight", "income",
)
GOLD_FUND_WORDS = ("gold",)

# The modules the advisor reads, in the order they're shown.
MODULES: dict[str, tuple[str, int | None]] = {
    # id: (label, phase)
    "budget": ("Budget health", 8),
    "goals": ("Goals", 8),
    "risk_profile": ("Risk profile", 7),
    "portfolio_plan": ("Portfolio plan", 7),
    "holdings": ("Your holdings", 2),
    "sectors": ("Sector trends", 6),
    "sentiment": ("News sentiment", 5),
    "predictions": ("Stock return ranges", 4),
}


# --- Rules (step 2) -------------------------------------------------------------

# Lower number = shown first. The order follows the usual financial-planning
# sequence: stop losing money each month, build a safety net, deal with
# heavy debt, fund goals, invest, then fine-tune. Our ordering of standard
# advice; not taken from one source.
PRIORITY: dict[str, int] = {
    "spending_exceeds_income": 10,
    "emergency_fund": 20,
    "debt_critical": 30,
    "debt_high": 35,
    "goal_unaffordable": 40,
    "invest_per_plan": 50,
    "rebalance": 60,
    "concentration": 65,
    "review_holding": 70,
    "not_in_plan": 80,
}

# Rebalance when an asset class is this many percentage points away from
# the plan. A common convention: Vanguard's rebalancing research
# (Jaconetti, Kinniry & Zilbering, "Best practices for portfolio
# rebalancing", 2010) compares bands and finds about 5 points a reasonable
# trade-off between risk control and trading costs.
REBALANCE_THRESHOLD_PP = 5.0
# Don't judge drift when we can't classify much of the portfolio.
MAX_UNCLASSIFIED_PCT_FOR_DRIFT = 25.0

# One stock above this share of everything invested is flagged. Same 15%
# as the Phase 7 per-stock cap (core/portfolio_config.py).
CONCENTRATION_PCT = 15.0

# "Review this holding" needs both: negative news on the stock AND its
# sector falling at least this much over a month. Either alone is noise.
REVIEW_SECTOR_FALL_PCT = -5.0


# --- Service (step 3) ------------------------------------------------------------

# Fresh advice per user per minute. Building it is cheap, but holdings may
# fetch fund NAVs (cached) and every call stores a document.
ADVICE_REQUESTS_PER_MINUTE = 10

